// =====================================================================
//  game_config.cpp —— 游戏的全部内容配置（唯一数据来源）
// =====================================================================
//
//  老板改游戏，只需要改这一个文件：
//    · 有哪几种盲盒、每种多少钱、卖价倍率（所有盲盒开局就能买）
//    · 每种盒子里有哪些手办（id、中文名、稀有度、描述、模型文件名）
//    · 各稀有度的掉率和基础卖价、单个手办的权重
//    · 保底、防重复、开局金币、破产补助
//
//  改完之后：
//    1. 双击 server/编译.bat（或在 VS Code 里按 Ctrl+Shift+B）重新编译
//    2. 重新运行 blindbox-server.exe
//    3. 启动时会自动检查配置；写错了（比如掉率加起来不是 1、id 重复）
//       会在黑窗口里用中文列出所有问题，不会启动
//
//  网页不写死任何手办，启动时从 GET /api/config 读取这里的内容。
//  想看导出的 JSON：blindbox-server --dump-config
//
//  通关条件：所有手办（现在是 21 个）都放进展柜。
//
//  模型：把 Lux3D 生成的 .glb 放进 exe 旁边的 models/ 文件夹，
//        文件名 = 下面每个手办的 model 字段（不写就是 "<id>.glb"）。
//        缺的模型会自动显示占位几何体，不会报错。
// =====================================================================

